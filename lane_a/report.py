"""Aggregation: cells in, publishable tables out. No number here is new.

Everything reported is a function of ``cells.jsonl`` and ``plan.json`` in a run
directory, so the tables can be regenerated by anyone holding the run, and the
rules that turn cells into rows are stated once, here:

* **The sampling unit is the scenario-repeat.** Success is reported two ways
  and both are published: the per-run rate over all repeats, and the observed
  all-repeats rate -- the share of scenarios in which *every* repeat passed.
  The second is what was seen, not a rate raised to a power: five runs give
  five outcomes, not a probability estimate dressed as one.
* **Confidence intervals are clustered bootstrap intervals**, resampling
  scenarios (for tasks) or repeats (for a single probe variant) with
  replacement, seeded so the interval is reproducible.
* **Latency is P50 and P90** until a declared minimum count; the tails need
  samples a handful of repeats does not have, and are withheld rather than
  reported from too few.
* **Gaps inside the detector's resolution are ties.** Two medians closer than
  the detector can resolve on clean audio are the same number.
* **Voids are counted, never scored**, and their reasons are tallied so an
  exclusion is visible as such.
* **Degradation is a delta from clean**, never an absolute, so a provider that
  is slow everywhere is not read as fragile.
* **Strata are never averaged across.** Configuration, caller voice and
  transform stay separate rows all the way to publication.

    python -m lane_a.report data/lane-a/<run> [more runs...] [--out report.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable, Sequence

import numpy as np

from lane_a.detector import FRAME_MS

MIN_TAIL_N = 30              # P95/P99 appear only at or above this many latencies
TIE_MS = FRAME_MS            # the detector's resolution on clean audio; see docs
BOOTSTRAP_DRAWS = 2000
BOOTSTRAP_SEED = 7
LATENCY_FIELDS = ("latency_ms", "stop_ms")   # the value a probe publishes as a duration

GroupKey = tuple[str, str, str, str, str]    # probe, variant, config, voice, transform


# ── loading ──────────────────────────────────────────────────────────────────

def load_run(run_dir: str | Path) -> dict[str, Any]:
    root = Path(run_dir)
    cells = [json.loads(line) for line in (root / "cells.jsonl").read_text().splitlines() if line.strip()]
    plan = json.loads((root / "plan.json").read_text())["cells"] if (root / "plan.json").exists() else []
    provenance = json.loads((root / "provenance.json").read_text()) if (root / "provenance.json").exists() else {}
    sentinel_ids = {p["cell_id"] for p in plan if p.get("sentinel")}
    for cell in cells:
        cell["sentinel"] = cell.get("artifacts", {}).get("slug") in sentinel_ids
        cell.setdefault("transform", "clean")
    return {"root": str(root), "provenance": provenance, "plan": plan, "cells": cells}


def key_of(cell: dict[str, Any]) -> GroupKey:
    return (cell["probe"], cell["variant"], cell["config"], cell["voice"], cell.get("transform", "clean"))


# ── statistics ───────────────────────────────────────────────────────────────

def _rng() -> np.random.Generator:
    return np.random.default_rng(BOOTSTRAP_SEED)


def bootstrap_ci(values: Sequence[float], statistic, draws: int = BOOTSTRAP_DRAWS) -> tuple[float, float] | None:
    """Percentile bootstrap interval of ``statistic`` over ``values``; None below two samples."""
    data = np.asarray(values, dtype=float)
    if data.size < 2:
        return None
    rng = _rng()
    samples = rng.choice(data, size=(draws, data.size), replace=True)
    stats = np.apply_along_axis(statistic, 1, samples)
    lo, hi = np.percentile(stats, [2.5, 97.5])
    return round(float(lo), 1), round(float(hi), 1)


def latency_summary(values: Sequence[float]) -> dict[str, Any]:
    clean = [float(v) for v in values if v is not None]
    if not clean:
        return {"n": 0}
    arr = np.asarray(clean)
    out: dict[str, Any] = {
        "n": int(arr.size),
        "p50": round(float(np.percentile(arr, 50)), 1),
        "p90": round(float(np.percentile(arr, 90)), 1),
        "min": round(float(arr.min()), 1),
        "max": round(float(arr.max()), 1),
        "p50_ci95": bootstrap_ci(clean, np.median),
    }
    if arr.size >= MIN_TAIL_N:
        out["p95"] = round(float(np.percentile(arr, 95)), 1)
        out["p99"] = round(float(np.percentile(arr, 99)), 1)
    else:
        out["tails_withheld"] = f"P95/P99 need n >= {MIN_TAIL_N}"
    return out


def rate_summary(passes: Sequence[bool]) -> dict[str, Any]:
    flags = [1.0 if p else 0.0 for p in passes]
    if not flags:
        return {"n": 0}
    ci = bootstrap_ci(flags, np.mean)
    return {
        "n": len(flags),
        "passed": int(sum(flags)),
        "rate": round(sum(flags) / len(flags), 4),
        "rate_ci95": None if ci is None else (round(ci[0] / 100.0 if ci[0] > 1 else ci[0], 4), round(ci[1] / 100.0 if ci[1] > 1 else ci[1], 4)),
    }


def clustered_success(clusters: dict[str, Sequence[bool]]) -> dict[str, Any]:
    """Per-run and all-repeats success over scenario clusters, with clustered bootstrap CIs.

    Resampling whole scenarios rather than individual repeats respects that
    repeats of one scenario are not independent draws: a scenario a model
    cannot do fails five times for one reason.
    """
    names = sorted(name for name, flags in clusters.items() if flags)
    if not names:
        return {"scenarios": 0}
    per_cluster = [np.asarray([1.0 if f else 0.0 for f in clusters[name]]) for name in names]

    def per_run(chosen: Iterable[int]) -> float:
        flat = np.concatenate([per_cluster[i] for i in chosen])
        return float(flat.mean())

    def all_repeats(chosen: Iterable[int]) -> float:
        return float(np.mean([per_cluster[i].all() for i in chosen]))

    everything = range(len(names))
    rng = _rng()
    draws = rng.integers(0, len(names), size=(BOOTSTRAP_DRAWS, len(names)))
    run_ci = np.percentile([per_run(d) for d in draws], [2.5, 97.5]) if len(names) > 1 else None
    all_ci = np.percentile([all_repeats(d) for d in draws], [2.5, 97.5]) if len(names) > 1 else None
    return {
        "scenarios": len(names),
        "repeats_per_scenario": {name: int(per_cluster[i].size) for i, name in enumerate(names)},
        "per_run_rate": round(per_run(everything), 4),
        "per_run_ci95": None if run_ci is None else (round(float(run_ci[0]), 4), round(float(run_ci[1]), 4)),
        "all_repeats_rate": round(all_repeats(everything), 4),
        "all_repeats_ci95": None if all_ci is None else (round(float(all_ci[0]), 4), round(float(all_ci[1]), 4)),
        "all_repeats_passed": [name for i, name in enumerate(names) if per_cluster[i].all()],
    }


def compare_medians(a: dict[str, Any], b: dict[str, Any], tie_ms: float = TIE_MS) -> dict[str, Any]:
    """Two latency summaries: which is lower, or a tie inside detector resolution."""
    if a.get("n", 0) == 0 or b.get("n", 0) == 0:
        return {"verdict": "incomparable"}
    gap = a["p50"] - b["p50"]
    if abs(gap) <= tie_ms:
        verdict = "tie"
    else:
        verdict = "a" if gap < 0 else "b"
    return {"verdict": verdict, "gap_ms": round(gap, 1), "tie_threshold_ms": tie_ms}


# ── one run ──────────────────────────────────────────────────────────────────

def _latency_field(cells: Sequence[dict[str, Any]]) -> str | None:
    for field in LATENCY_FIELDS:
        if any(field in c.get("values", {}) for c in cells):
            return field
    return None


def summarize_group(cells: Sequence[dict[str, Any]]) -> dict[str, Any]:
    scored = [c for c in cells if not c.get("void")]
    voids: dict[str, int] = defaultdict(int)
    for cell in cells:
        if cell.get("void"):
            voids[_void_class(cell["void"])] += 1
    out: dict[str, Any] = {"cells": len(cells), "scored": len(scored), "voids": dict(voids)}
    field = _latency_field(scored)
    if field:
        out["latency_field"] = field
        out["latency"] = latency_summary([c["values"].get(field) for c in scored])
    if any(c.get("verdict") in ("pass", "fail") for c in scored):
        out["success"] = rate_summary([c["verdict"] == "pass" for c in scored if c.get("verdict") in ("pass", "fail")])
    return out


def _void_class(reason: str) -> str:
    if reason.startswith("configuration not supported"):
        return "excluded: " + reason.split(": ", 1)[1]
    if reason.startswith("provider refused"):
        return "provider refused the session"
    if reason.startswith("harness error"):
        return "harness error"
    if "slipped" in reason:
        return "caller pacing slipped"
    return reason


def summarize_run(run: dict[str, Any]) -> dict[str, Any]:
    cells = run["cells"]
    prov = run["provenance"]
    groups: dict[GroupKey, list[dict[str, Any]]] = defaultdict(list)
    for cell in cells:
        if not cell.get("sentinel"):
            groups[key_of(cell)].append(cell)

    report: dict[str, Any] = {
        "run_id": prov.get("run_id", Path(run["root"]).name),
        "provider": prov.get("provider"),
        "model": prov.get("model"),
        "methodology_version": prov.get("methodology_version"),
        "harness_commit": (prov.get("harness") or {}).get("commit"),
        "harness_dirty": (prov.get("harness") or {}).get("dirty"),
        "corpus_version": prov.get("corpus_version"),
        "counts": {
            "planned": len(run["plan"]) or None,
            "completed": len(cells),
            "voids": sum(1 for c in cells if c.get("void")),
            "errors": sum(1 for c in cells if c.get("error")),
        },
        "rules": {
            "tie_ms": TIE_MS, "min_tail_n": MIN_TAIL_N, "bootstrap_draws": BOOTSTRAP_DRAWS, "bootstrap_seed": BOOTSTRAP_SEED,
        },
        "sentinel": summarize_group([c for c in cells if c.get("sentinel")]) if any(c.get("sentinel") for c in cells) else None,
        "groups": {
            "/".join(key): summarize_group(members) for key, members in sorted(groups.items())
        },
    }

    # Tasks: clusters are scenarios (variants), within one config/voice/transform/modality.
    tasks: dict[tuple[str, str, str, str], dict[str, list[bool]]] = defaultdict(lambda: defaultdict(list))
    for cell in cells:
        if cell.get("probe") == "task" and not cell.get("void") and cell.get("verdict") in ("pass", "fail"):
            modality = cell.get("values", {}).get("modality", "audio")
            tasks[(cell["config"], cell["voice"], cell.get("transform", "clean"), modality)][cell["variant"]].append(cell["verdict"] == "pass")
    report["tasks"] = {
        f"{config}/{voice}/{transform}/{modality}": clustered_success(clusters)
        for (config, voice, transform, modality), clusters in sorted(tasks.items())
    }

    # Degradation: the delta of each degraded stratum from its clean twin.
    deltas: dict[str, Any] = {}
    for key, summary in report["groups"].items():
        probe, variant, config, voice, transform = key.split("/")
        if transform == "clean":
            continue
        clean = report["groups"].get("/".join((probe, variant, config, voice, "clean")))
        if not clean:
            continue
        entry: dict[str, Any] = {"transform": transform}
        if "latency" in summary and "latency" in clean and summary["latency"].get("n") and clean["latency"].get("n"):
            entry["p50_delta_ms"] = round(summary["latency"]["p50"] - clean["latency"]["p50"], 1)
        if "success" in summary and "success" in clean and summary["success"].get("n") and clean["success"].get("n"):
            entry["rate_delta"] = round(summary["success"]["rate"] - clean["success"]["rate"], 4)
        entry["void_delta"] = sum(summary["voids"].values()) - sum(clean["voids"].values())
        deltas[key] = entry
    report["degradation_deltas"] = deltas
    return report


# ── across runs ──────────────────────────────────────────────────────────────

def compare_runs(reports: Sequence[dict[str, Any]]) -> dict[str, Any]:
    """Side by side, group by group, with ties declared where the detector cannot tell."""
    keys = sorted({key for r in reports for key in r["groups"]})
    table: dict[str, Any] = {}
    for key in keys:
        row = {}
        for report in reports:
            summary = report["groups"].get(key)
            if not summary:
                continue
            label = f"{report['provider']}:{report['model']}"
            row[label] = {
                "p50": (summary.get("latency") or {}).get("p50"),
                "p50_ci95": (summary.get("latency") or {}).get("p50_ci95"),
                "rate": (summary.get("success") or {}).get("rate"),
                "n": summary.get("scored"),
                "voids": sum(summary.get("voids", {}).values()),
            }
        with_latency = [(label, r) for label, r in row.items() if r["p50"] is not None]
        if len(with_latency) >= 2:
            ordered = sorted(with_latency, key=lambda item: item[1]["p50"])
            best, runner_up = ordered[0], ordered[1]
            gap = runner_up[1]["p50"] - best[1]["p50"]
            row["_lowest_p50"] = {"label": best[0], "gap_to_next_ms": round(gap, 1), "tie": gap <= TIE_MS}
        table[key] = row
    sentinels = {
        f"{r['provider']}:{r['model']}@{r['run_id']}": (r.get("sentinel") or {}).get("latency")
        for r in reports
    }
    return {"groups": table, "sentinels": sentinels}


# ── rendering ────────────────────────────────────────────────────────────────

def _fmt_ci(ci: Any) -> str:
    return "" if not ci else f" [{ci[0]}, {ci[1]}]"


def render_markdown(report: dict[str, Any]) -> str:
    lines = [
        f"# {report['provider']} / {report['model']}",
        "",
        f"run `{report['run_id']}` · methodology `{report['methodology_version']}` · harness `{report['harness_commit']}`"
        + (" (dirty)" if report.get("harness_dirty") else "") + f" · corpus `{report['corpus_version']}`",
        "",
        f"cells {report['counts']['completed']}/{report['counts']['planned']} · voids {report['counts']['voids']} · errors {report['counts']['errors']}",
        "",
    ]
    if report.get("sentinel") and report["sentinel"].get("latency", {}).get("n"):
        lat = report["sentinel"]["latency"]
        lines += [f"**Sentinel** (fixed cell, n={lat['n']}): P50 {lat['p50']} ms{_fmt_ci(lat.get('p50_ci95'))}, spread {lat['min']}–{lat['max']} ms", ""]
    lines += ["| probe / variant | config | voice | transform | n | P50 ms | 95% CI | P90 ms | pass rate | voids |", "|---|---|---|---|---|---|---|---|---|---|"]
    for key, summary in report["groups"].items():
        probe, variant, config, voice, transform = key.split("/")
        lat = summary.get("latency") or {}
        suc = summary.get("success") or {}
        lines.append(
            f"| {variant} | {config} | {voice} | {transform} | {summary['scored']} | "
            f"{lat.get('p50', '')} | {_fmt_ci(lat.get('p50_ci95')).strip()} | {lat.get('p90', '')} | "
            f"{'' if not suc else f'{suc['passed']}/{suc['n']}'} | {sum(summary['voids'].values())} |"
        )
    if report.get("tasks"):
        lines += ["", "## Tasks (clusters are scenarios)", "", "| stratum | scenarios | per-run rate | 95% CI | all-repeats rate | 95% CI |", "|---|---|---|---|---|---|"]
        for stratum, t in report["tasks"].items():
            if not t.get("scenarios"):
                continue
            lines.append(
                f"| {stratum} | {t['scenarios']} | {t['per_run_rate']} | {_fmt_ci(t.get('per_run_ci95')).strip()} | "
                f"{t['all_repeats_rate']} | {_fmt_ci(t.get('all_repeats_ci95')).strip()} |"
            )
    if report.get("degradation_deltas"):
        lines += ["", "## Degradation, as delta from clean", "", "| stratum | transform | ΔP50 ms | Δ pass rate | Δ voids |", "|---|---|---|---|---|"]
        for key, d in report["degradation_deltas"].items():
            lines.append(f"| {key} | {d['transform']} | {d.get('p50_delta_ms', '')} | {d.get('rate_delta', '')} | {d['void_delta']} |")
    voids: dict[str, int] = defaultdict(int)
    for summary in report["groups"].values():
        for reason, count in summary["voids"].items():
            voids[reason] += count
    if voids:
        lines += ["", "## Voids", ""] + [f"- {count} × {reason}" for reason, count in sorted(voids.items(), key=lambda kv: -kv[1])]
    lines += ["", f"Rules: ties within {TIE_MS} ms · P95/P99 withheld under n={MIN_TAIL_N} · bootstrap {BOOTSTRAP_DRAWS} draws, seed {BOOTSTRAP_SEED}"]
    return "\n".join(lines) + "\n"


def render_comparison(comparison: dict[str, Any]) -> str:
    lines = ["# Across providers", "", "Lowest P50 per stratum; a gap inside detector resolution is a tie, not a ranking.", ""]
    for key, row in comparison["groups"].items():
        lowest = row.get("_lowest_p50")
        cols = [f"{label}: P50 {r['p50']} ms{_fmt_ci(r['p50_ci95'])}" if r["p50"] is not None else f"{label}: pass {r['rate']}" if r["rate"] is not None else f"{label}: n={r['n']}"
                for label, r in row.items() if not label.startswith("_")]
        verdict = "" if not lowest else (f" → tie ({lowest['gap_to_next_ms']} ms)" if lowest["tie"] else f" → lowest {lowest['label']} by {lowest['gap_to_next_ms']} ms")
        lines.append(f"- **{key}** · " + " · ".join(cols) + verdict)
    lines += ["", "## Sentinels", ""] + [f"- {label}: P50 {lat['p50']} ms, spread {lat['min']}–{lat['max']} ms (n={lat['n']})" if lat and lat.get("n") else f"- {label}: none" for label, lat in comparison["sentinels"].items()]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("runs", nargs="+")
    parser.add_argument("--out", help="markdown file for the cross-run comparison")
    args = parser.parse_args(argv)
    reports = []
    for run_dir in args.runs:
        run = load_run(run_dir)
        report = summarize_run(run)
        reports.append(report)
        Path(run_dir, "report.json").write_text(json.dumps(report, indent=2) + "\n")
        Path(run_dir, "report.md").write_text(render_markdown(report))
        print(f"{run_dir}: report.json, report.md")
    if len(reports) > 1:
        comparison = compare_runs(reports)
        text = render_comparison(comparison)
        if args.out:
            Path(args.out).write_text(text)
            print(f"comparison -> {args.out}")
        else:
            print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
